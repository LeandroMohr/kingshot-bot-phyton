function tr(key, params = {}) {
  const text = STRINGS[lang][key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

function setLang(value) {
  lang = LANGUAGES[value] ? value : DEFAULT_LANG;
  localStorage.setItem("lang", lang);
  applyStaticTexts();
}

// Texts written in index.html: data-i18n (text), data-i18n-placeholder, data-i18n-title.
function applyStaticTexts() {
  document.documentElement.lang = lang;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = tr(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = tr(node.dataset.i18nPlaceholder);
  for (const node of document.querySelectorAll("[data-i18n-title]")) node.title = tr(node.dataset.i18nTitle);
}
